#!/usr/bin/env node
// Generates the homepage illustration: a plant drawn as PCB traces. Stems are
// routed on 45 degree angles from an edge connector, vias mark the joints, and
// the traces end in leaves.
//
//   node plugins/home/scripts/vine.mjs   # writes src/components/vine.ts
//
// Then rebuild the plugin (node plugins/build.mjs home). The classes on the
// shapes (t = trace, l = leaf, f = leaf fill, r = leaf rib, v = via, p = pad)
// are styled in src/components/styles/home.scss; --d is the delay, in seconds,
// before a shape draws in.
import { writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const DIR = {
  N: [0, -1],
  NE: [1, -1],
  E: [1, 0],
  SE: [1, 1],
  S: [0, 1],
  SW: [-1, 1],
  W: [-1, 0],
  NW: [-1, -1],
}
const r = (n) => Math.round(n * 10) / 10

// route("x,y", "N 40", "NE 20", ...) -> { points, end, dir }
function route(start, ...steps) {
  let [x, y] = start
  const points = [[x, y]]
  let dir = [0, -1]
  for (const step of steps) {
    const [d, len] = step.split(" ")
    dir = DIR[d]
    const l = Number(len)
    x += dir[0] * l
    y += dir[1] * l
    points.push([x, y])
  }
  return { points, end: [x, y], dir }
}

const trace = (points, delay) =>
  `<path class="t" style="--d:${delay}s" pathLength="1" d="M${points.map((p) => p.map(r).join(" ")).join("L")}"/>`

// almond leaf from `base`, pointing along `dir`, `len` long
function leaf(base, dir, len, delay, filled = true) {
  const n = Math.hypot(dir[0], dir[1])
  const ux = dir[0] / n,
    uy = dir[1] / n
  const px = -uy,
    py = ux
  const w = len * 0.34
  const tip = [base[0] + ux * len, base[1] + uy * len]
  const c1 = [base[0] + ux * len * 0.45 + px * w, base[1] + uy * len * 0.45 + py * w]
  const c2 = [base[0] + ux * len * 0.45 - px * w, base[1] + uy * len * 0.45 - py * w]
  const rib = [base[0] + ux * len * 0.62, base[1] + uy * len * 0.62]
  const f = (p) => p.map(r).join(" ")
  return `<g class="l" style="--d:${delay}s"><path ${filled ? 'class="f"' : ""} d="M${f(base)}Q${f(c1)} ${f(tip)}Q${f(c2)} ${f(base)}Z"/><path class="r" d="M${f(base)}L${f(rib)}"/></g>`
}

const via = (p, delay, big = false) =>
  `<circle class="v" style="--d:${delay}s" cx="${r(p[0])}" cy="${r(p[1])}" r="${big ? 5.5 : 4}"/>`

const out = []
const leaves = []
const vias = []
const W = 340,
  H = 500
const baseY = 470

// edge connector: five pads, the plant grows out of them
const pads = [110, 140, 170, 200, 230]
const padSvg = pads
  .map(
    (x, i) =>
      `<rect class="p" style="--d:${i * 0.05}s" x="${x - 7}" y="${baseY}" width="14" height="26" rx="3"/>`,
  )
  .join("")

// main stem, from the middle pad
const stem = route([170, baseY], "N 60", "NW 25", "N 70", "NE 35", "N 80", "NW 20", "N 60")
out.push(trace(stem.points, 0.1))
leaves.push(leaf(stem.end, [0, -1], 58, 1.5))

// branches off the stem: [start, steps, leaf length (0 = via), delay, leaf direction]
const branches = [
  [[145, 350], ["NW 24", "W 30"], 48, 0.6, [-1, -0.4]],
  [[163, 297], ["E 44"], 0, 0.8],
  [[180, 262], ["NE 26", "E 40"], 52, 0.95, [1, -0.3]],
  [[180, 240], ["NW 30", "W 34"], 48, 1.05, [-1, -0.45]],
  [[180, 200], ["NE 24", "N 28", "NE 16"], 44, 1.2, [0.8, -1]],
  [[160, 150], ["NW 24", "N 18"], 40, 1.4, [-0.5, -1]],
]
vias.push(via([145, 315], 0.7))
for (const [start, steps, len, delay, dir] of branches) {
  const b = route(start, ...steps)
  out.push(trace(b.points, delay))
  vias.push(via(start, delay))
  if (len) leaves.push(leaf(b.end, dir ?? b.dir, len, delay + 0.35))
  else vias.push(via(b.end, delay + 0.3, true))
}

// side traces from the other pads: pure circuitry, they end in a via or a leaf
const sides = [
  [[110, baseY], ["N 24", "NW 34", "N 27"], 40, 0.2, [-0.6, -1]],
  [[140, baseY], ["N 40", "NW 16", "N 18"], 0, 0.15],
  [[200, baseY], ["N 34", "NE 18", "N 30"], 0, 0.15],
  [[230, baseY], ["N 20", "NE 38", "N 34"], 42, 0.25, [0.7, -1]],
]
for (const [start, steps, len, delay, dir] of sides) {
  const b = route(start, ...steps)
  out.push(trace(b.points, delay))
  if (len) leaves.push(leaf(b.end, dir ?? b.dir, len, delay + 0.6))
  else vias.push(via(b.end, delay + 0.5, true))
}

const svg = `<svg viewBox="0 0 ${W} ${H}" xmlns="http://www.w3.org/2000/svg" fill="none" stroke="currentColor" stroke-linecap="round" stroke-linejoin="round">${padSvg}<g stroke-width="2.25">${out.join("")}</g><g stroke-width="1.75">${leaves.join("")}</g><g stroke-width="2.25">${vias.join("")}</g></svg>`

const target = path.join(path.dirname(fileURLToPath(import.meta.url)), "../src/components/vine.ts")
writeFileSync(
  target,
  `// Generated by ../../scripts/vine.mjs. Do not edit by hand.\nexport const vine =\n  '${svg}'\n`,
)
console.log(`wrote ${target} (${svg.length} bytes)`)
